"""Offline MCP-import regression tests. No account or network calls."""
import copy
import json
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'engine'))
import notion_index as ni

class IndexTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        self.file = self.root / 'cafe.mp4'
        self.file.write_bytes(b'fixture')
        self.layout = {'roles': {'broll': {'data_source_id': 'ds', 'title_property': 'Name', 'files_property': 'Files & media'}}}
        self.row = {'id': 'page-a', 'role': 'broll', 'title': 'coffee downtown', 'body': 'CC0 stock scene', 'last_edited_time': 'v1', 'files': [{'name': 'cafe.mp4', 'ref': 'asset-a', 'path': str(self.file)}]}
        self.inventory = {'complete_roles': ['broll'], 'rows': [self.row]}
        self.idx = ni.empty_index()
    def refresh(self, rows=None, inventory=None):
        with patch.object(ni, 'media_info', return_value={'width': 720, 'height': 1280, 'duration': 5, 'aspect': 'vertical'}), patch.object(ni, 'make_local_poster', return_value=str(self.file)):
            return ni.refresh(self.idx, self.layout, inventory or self.inventory, rows or [self.row], self.root)
    def test_detect_both_schemas(self):
        for title, files in [('Name','Files & media'),('Description of Graphic','File')]:
            role = ni.detect_role({'database_id':'db','data_source_id':'ds','schema':{title:{'type':'title'},files:{'type':'files'},'Tags':{'type':'multi_select'}}})
            self.assertEqual(role['title_property'],title)
            self.assertEqual(role['files_property'],files)
            self.assertEqual(role['tags_property'],'Tags')
    def test_ambiguous_schema_rejected(self):
        with self.assertRaises(ValueError):ni.detect_role({'schema':{'A':{'type':'title'},'B':{'type':'files'},'C':{'type':'files'}}})
    def test_refresh_and_unchanged(self):
        result=self.refresh();self.assertEqual(result['reread'],['page-a'])
        self.assertEqual(ni.plan(self.idx,self.inventory)['fetch'],[])
        self.assertEqual(len(self.idx['entries']),1)
        e=next(iter(self.idx['entries'].values()));self.assertEqual(e['sha256'],ni.sha256(self.file));self.assertIn('skyline',e['tags'])
    def test_two_changes_and_override(self):
        self.refresh();ni.set_override(self.idx,'page-a',{'tags_add':['favorite'],'tags_remove':['downtown'],'origin':'ai'})
        renamed=copy.deepcopy(self.row);renamed.update(title='neon sign',last_edited_time='v2')
        new=copy.deepcopy(self.row);new['id']='page-b'
        inventory={'complete_roles':['broll'],'rows':[renamed,new]}
        self.assertEqual(ni.plan(self.idx,inventory)['fetch'],['page-a','page-b'])
        self.refresh([renamed,new],inventory)
        e=next(e for e in self.idx['entries'].values() if e['page_id']=='page-a')
        self.assertEqual(e['title'],'neon sign');self.assertIn('favorite',ni.effective(e,self.idx)['tags']);self.assertEqual(ni.effective(e,self.idx)['origin'],'ai')
    def test_changed_hash_and_stale(self):
        self.refresh();self.file.write_bytes(b'changed')
        self.assertEqual(ni.plan(self.idx,self.inventory)['fetch'],['page-a'])
        self.refresh();self.assertEqual(len(self.idx['entries']),2)
        self.assertEqual(sum(not e['stale'] for e in self.idx['entries'].values()),1)
        ni.refresh(self.idx,self.layout,{'complete_roles':['broll'],'rows':[]},[],self.root)
        self.assertTrue(all(e['stale'] for e in self.idx['entries'].values()))
    def test_partial_inventory_does_not_stale(self):
        self.refresh();ni.refresh(self.idx,self.layout,{'complete_roles':[],'rows':[]},[],self.root)
        self.assertFalse(next(iter(self.idx['entries'].values()))['stale'])
    def test_missing_changed_page_rejected(self):
        with self.assertRaises(ValueError):ni.refresh(self.idx,self.layout,self.inventory,[],self.root)
        self.assertEqual(self.idx,ni.empty_index())
    def test_ai_words_and_boundaries(self):
        self.assertEqual(ni.infer_origin('Veo cafe','',[]),'ai')
        self.assertEqual(ni.infer_origin('chair at station','',[]),'stock')
        self.assertEqual(ni.infer_origin('clip','generated by Sora',[]),'ai')
    def test_ranking_and_filters(self):
        self.refresh();hits=ni.find(self.idx,'city cafe',origin='stock',aspect='vertical')
        self.assertTrue(hits);self.assertTrue(hits[0]['match_reasons']);self.assertGreater(hits[0]['score'],0)
        self.assertEqual(ni.find(self.idx,'cafe',origin='ai'),[])
        ni.set_override(self.idx,'page-a',{'exclude':True});self.assertEqual(ni.find(self.idx,'cafe'),[])
    def test_body_edit_timestamp(self):
        self.refresh();r=copy.deepcopy(self.row);r['last_edited_time']='v2'
        self.assertEqual(ni.plan(self.idx,{'rows':[r]})['fetch'],['page-a'])
    def test_custom_workflow_names(self):
        c={'workflow':'posts','workflow_settings':{'status_property':'State','flag_property':'Flag','edit_statuses':['Cutting'],'review_status':'Check','posted_status':'Live','failure_flag':'Fix'}}
        row={'id':'x','properties':{'State':'Cutting'}}
        self.assertEqual(ni.transition(c,row,'PASS')['local_status'],{'State':'Check'})
        self.assertEqual(ni.transition(c,row,'FAIL')['local_status'],{'Flag':'Fix'})
        with self.assertRaises(ValueError):ni.transition(c,row,'PASS',requested='Live')
        row['properties']['State']='Check'
        self.assertEqual(ni.transition(c,row,'PASS',human_posted=True,simulated=True)['local_status']['State'],'Live')
    def test_videos_workflow(self):
        c={'workflow':'videos','workflow_settings':{'status_property':'Stage','edit_statuses':['Editing'],'review_status':'Done','qa_property':'QA','failure_status':'QA failed'}}
        row={'id':'x','properties':{'Stage':'Editing'}}
        self.assertEqual(ni.transition(c,row,'PASS')['local_status'],{'Stage':'Done','QA':'Pass'})
        self.assertEqual(ni.transition(c,row,'FAIL')['local_status'],{'Stage':'QA failed','QA':'Fail'})
    def test_pass_clears_only_configured_failure_flag(self):
        c={'workflow':'posts','workflow_settings':{'status_property':'Status','edit_statuses':['Editing'],'review_status':'In review','posted_status':'Posted','flag_property':'Flag','failure_flag':'Needs fix'}}
        row={'id':'x','properties':{'Status':'Editing','Flag':'Needs fix'}}
        self.assertIsNone(ni.transition(c,row,'PASS')['local_status']['Flag'])
        row['properties']['Flag']='Hold'
        self.assertNotIn('Flag',ni.transition(c,row,'PASS')['local_status'])
    def test_minimal_inventory_accepts_fetched_timestamp(self):
        inv=copy.deepcopy(self.inventory);inv['rows'][0].pop('last_edited_time')
        self.refresh(inventory=inv)
        self.assertEqual(ni.plan(self.idx,inv)['fetch'],[])
        self.assertEqual(next(iter(self.idx['entries'].values()))['last_edited_time'],'v1')
    def test_legacy_videos_role_without_files(self):
        result=ni.detect({'workflow':'videos','roles':{'videos':{'schema':{'Name':{'type':'title'},'Raw footage':{'type':'url'}}}}})
        self.assertIsNone(result['roles']['videos']['files_property'])
        self.assertEqual(result['roles']['videos']['input_property'],'Raw footage')
    def test_raw_mcp_schema(self):
        raw={'content':[{'type':'text','text':json.dumps({'text':'<data-source-state>\n'+json.dumps({'schema':{'Description of Graphic':{'type':'title'},'Files & media':{'type':'file'}}})+'\n</data-source-state>'})}]}
        self.assertEqual(ni.detect_role({'fetch':raw})['title_property'],'Description of Graphic')

    def test_saved_view_can_omit_hash_and_timestamp(self):
        self.row['files'][0]['sha256'] = ni.sha256(self.file)
        self.refresh()
        view = copy.deepcopy(self.inventory)
        view['rows'][0].pop('last_edited_time')
        view['rows'][0]['files'][0].pop('sha256')
        self.assertEqual(ni.plan(self.idx, view)['fetch'], [])
        view['rows'][0]['files'][0]['ref'] = 'new-upload'
        self.assertEqual(ni.plan(self.idx, view)['fetch'], ['page-a'])

    def test_invalid_workflow_fails_closed(self):
        with self.assertRaises(ValueError):ni.transition({'workflow':'posts'}, {'id':'x'},'PASS')
        with self.assertRaises(ValueError):ni.transition({'workflow':'posts','workflow_settings':{'status_property':'Status','edit_statuses':['Editing'],'review_status':'Posted','posted_status':'Posted'}},{'id':'x','properties':{'Status':'Editing'}},'PASS')

    def test_plain_title_strips_mcp_markup(self):
        self.assertEqual(ni.plain_title(r'IMG\_1234'), 'IMG_1234')
        self.assertEqual(ni.plain_title('[cafe.mp](https://example.invalid/file)4'), 'cafe.mp4')
        self.assertEqual(ni.plain_title('coffee downtown'), 'coffee downtown')

    def test_markdown_title_indexes_as_plain(self):
        self.row['title'] = r'IMG\_1234'
        self.inventory['rows'][0]['title'] = r'IMG\_1234'
        self.refresh()
        self.assertEqual(next(iter(self.idx['entries'].values()))['title'], 'IMG_1234')
        view = copy.deepcopy(self.inventory)
        view['rows'][0]['title'] = 'IMG_1234'
        self.assertEqual(ni.plan(self.idx, view)['fetch'], [])

    def _upload_layout(self):
        return {'workspace_id': 'workspace-authorized', 'hub_id': 'hub-authorized', 'asset_upload': 'authorized_hub',
                'notion_writeback': False,
                'roles': {'broll': {'database_id': 'db-broll', 'data_source_id': 'ds-broll', 'title_property': 'Name', 'files_property': 'Files & media'},
                          'pictures': {'database_id': 'db-pictures', 'title_property': 'Name', 'files_property': 'Files & media'},
                          'styles': {'database_id': 'db-styles', 'title_property': 'Name', 'files_property': 'Files & media'}}}

    def test_upload_scoped_to_authorized_hub(self):
        plan = ni.upload_plan(self._upload_layout(), role='broll', title='cafe night', local_file=self.file, origin='ai')
        self.assertTrue(plan['notion_writeback'])
        self.assertFalse(plan['write_performed'])
        self.assertEqual(plan['scope'], 'authorized_hub')
        self.assertEqual(plan['workspace_id'], 'workspace-authorized')
        self.assertEqual(plan['hub_id'], 'hub-authorized')
        self.assertEqual(plan['database_id'], 'db-broll')
        self.assertEqual(plan['properties'], {'Name': 'cafe night'})
        self.assertEqual(plan['files_property'], 'Files & media')
        self.assertEqual(plan['schema_columns_added'], [])
        self.assertIn('not a licence clearance', plan['body'])
        self.assertFalse(plan['poster_upload'])
        dashed = 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa'
        same = ni.upload_plan(self._upload_layout() | {'workspace_id': 'a' * 32, 'hub_id': dashed},
                              role='styles', title='look', local_file=self.file,
                              workspace_id='aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa', hub_id='a' * 32)
        self.assertEqual(same['role'], 'styles')
        self.assertEqual(set(same['properties']), {'Name'})

    def test_upload_refuses_other_workspace_or_hub(self):
        layout = self._upload_layout()
        with self.assertRaises(ValueError):
            ni.upload_plan(layout, role='broll', title='cafe', local_file=self.file, workspace_id='workspace-other')
        with self.assertRaises(ValueError):
            ni.upload_plan(layout, role='pictures', title='cafe', local_file=self.file, hub_id='hub-other')
        with self.assertRaises(ValueError):
            ni.upload_plan({'roles': layout['roles']}, role='broll', title='cafe', local_file=self.file)
        with self.assertRaises(ValueError):
            ni.upload_plan(layout | {'asset_upload': 'off'}, role='broll', title='cafe', local_file=self.file)

    def test_upload_does_not_invent_columns_or_roles(self):
        layout = self._upload_layout()
        with self.assertRaises(ValueError):
            ni.upload_plan(layout, role='graphics', title='card', local_file=self.file)
        with self.assertRaises(ValueError):
            ni.upload_plan(layout, role='posts', title='queue', local_file=self.file)
        bare = {'workspace_id': 'workspace-authorized', 'hub_id': 'hub-authorized', 'asset_upload': 'authorized_hub',
                'roles': {'broll': {'title_property': 'Name', 'files_property': 'Files & media'}}}
        with self.assertRaises(ValueError):
            ni.upload_plan(bare, role='broll', title='cafe', local_file=self.file)
        missing_files = {'workspace_id': 'workspace-authorized', 'hub_id': 'hub-authorized', 'asset_upload': 'authorized_hub',
                         'roles': {'styles': {'database_id': 'db-styles', 'title_property': 'Name'}}}
        with self.assertRaises(ValueError):
            ni.upload_plan(missing_files, role='style', title='look', local_file=self.file)

    def test_styles_role_indexes_as_style(self):
        self.layout = {'roles': {'styles': {'title_property': 'Name', 'files_property': 'Files & media'}}}
        self.row['role'] = 'styles'
        self.inventory['rows'][0]['role'] = 'styles'
        self.inventory['complete_roles'] = ['styles']
        self.refresh()
        self.assertEqual(next(iter(self.idx['entries'].values()))['kind'], 'style')

if __name__ == '__main__':unittest.main()
